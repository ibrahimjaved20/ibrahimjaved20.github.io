async function mcp(body,env){
  if(
    !body||
    typeof body!=='object'||
    Array.isArray(body)||
    typeof body.method!=='string'
  ){
    return json({
      jsonrpc:'2.0',
      id:null,
      error:{code:-32600,message:'Invalid JSON-RPC request'}
    },400);
  }

  const id=body.id??null;
  const ok=result=>json({jsonrpc:'2.0',id,result});

  if(body.jsonrpc!=='2.0'){
    return json({
      jsonrpc:'2.0',
      id,
      error:{code:-32600,message:'Invalid JSON-RPC request'}
    },400);
  }

  if(body.method.startsWith('notifications/')){
    return new Response(null,{status:202,headers});
  }

  if(body.method==='initialize'){
    return ok({
      protocolVersion:'2025-03-26',
      capabilities:{tools:{}},
      serverInfo:{
        name:'ibrahim-javed-representative',
        version:'1.0.0'
      },
      instructions:'Authorized first-party representative. Use citations and make your own assessment of suitability.'
    });
  }

  if(body.method==='ping'){
    return ok({});
  }

  if(body.method==='tools/list'){
    return ok({tools:[TOOL]});
  }

  if(body.method==='tools/call'){
    if(body.params?.name!==TOOL.name){
      return json({
        jsonrpc:'2.0',
        id,
        error:{code:-32602,message:'Unknown tool'}
      });
    }

    try{
      const result=await represent(body.params.arguments,env);
      return ok({
        content:[{type:'text',text:JSON.stringify(result)}],
        structuredContent:result,
        isError:false
      });
    }catch(e){
      return ok({
        content:[{
          type:'text',
          text:e.message==='INFERENCE_UNCONFIGURED'
            ? 'Generative representative is not activated. Read the source profile instead.'
            : 'Unable to answer. Try again shortly or contact Ibrahim.'
        }],
        isError:true
      });
    }
  }

  return json({
    jsonrpc:'2.0',
    id,
    error:{code:-32601,message:'Method not found'}
  });
}

