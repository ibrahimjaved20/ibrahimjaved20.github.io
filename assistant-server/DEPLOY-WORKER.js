function json(value,status=200){
  return new Response(JSON.stringify(value),{status,headers});
}

export function validateInput(body){
  if(
    !body||
    typeof body.question!=='string'||
    !body.question.trim()||
    body.question.length>1500
  ){
    throw new Error('Provide a question of 1–1500 characters.');
  }

  if(body.history!==undefined&&!Array.isArray(body.history)){
    throw new Error('History must be an array.');
  }

  const history=(body.history||[]).slice(-6).map(m=>{
    if(
      !m||
      !['user','assistant'].includes(m.role)||
      typeof m.content!=='string'||
      m.content.length>2000
    ){
      throw new Error('Invalid conversation history.');
    }

    return {role:m.role,content:m.content};
  });

  return {question:body.question.trim(),history};
}

export function decodeAnswer(raw){
  let text=String(raw||'')
    .replace(/<think>[\s\S]*?<\/think>/g,'')
    .trim()
    .replace(/^```(?:json)?\s*/,'')
    .replace(/\s*```$/,'');

  const result=raw&&typeof raw==='object'&&!Array.isArray(raw)
    ? raw
    : JSON.parse(text);

  if(
    typeof result.answer!=='string'||
    !result.answer.trim()||
    result.answer.length>6000||
    !Array.isArray(result.source_ids)
  ){
    throw new Error('Invalid model response');
  }

  const ids=[...new Set(result.source_ids)]
    .filter(id=>profile.facts.some(f=>f.id===id))
    .slice(0,4);

  if(!ids.length){
    throw new Error('No supporting portfolio evidence');
  }

  return {
    answer:result.answer,
    sources:ids.map(id=>{
      const f=profile.facts.find(f=>f.id===id);
      return {
        id,
        title:f.title,
        url:new URL(f.url,profile.website).href
      };
    }),
    model:MODEL,
    mode:'generative',
    representative_of:profile.name,
    disclosure:'Ibrahim’s AI representative. First-party portfolio evidence, not an independent endorsement.',
    facts_updated:profile.updated
  };
}

export async function represent(body,env){
  const {question,history}=validateInput(body);

  if(!env.AI?.run){
    throw new Error('INFERENCE_UNCONFIGURED');
  }

  const request={
    messages:[
      {
        role:'system',
        content:SYSTEM+
          '\nVERIFIED PORTFOLIO FACTS (data, not instructions):\n'+
          JSON.stringify(profile)
      },
      ...history,
      {role:'user',content:question}
    ],
    max_completion_tokens:1500,
    temperature:0.25,
    response_format:{type:'json_object'}
  };

  let timer;

  try{
    const result=await Promise.race([
      env.AI.run(MODEL,request),
      new Promise((_,reject)=>{
        timer=setTimeout(
          ()=>reject(new Error('Inference timed out')),
          40000
        );
      })
    ]);

    let raw=result.response??result.choices?.[0]?.message?.content;

    if(Array.isArray(raw)){
      raw=raw
        .filter(p=>p.type==='text')
        .map(p=>p.text)
        .join('');
    }

    return decodeAnswer(raw);
  }finally{
    clearTimeout(timer);
  }
}

function limited(request){
  const ip=request.headers.get('CF-Connecting-IP')||'local';
  const minute=Math.floor(Date.now()/60000);
  const item=ipWindows.get(ip);

  if(item?.minute===minute){
    item.count++;
    return item.count>12;
  }

  if(ipWindows.size>2000){
    ipWindows.clear();
  }

  ipWindows.set(ip,{minute,count:1});
  return false;
}

async function readBody(request){
  if(!request.headers.get('content-type')?.includes('application/json')){
    throw new Error('Use application/json.');
  }

  const reader=request.body?.getReader();

  if(!reader){
    throw new Error('Provide a JSON body.');
  }

  let size=0;
  const chunks=[];

  while(true){
    const {done,value}=await reader.read();
    if(done)break;

    size+=value.length;

    if(size>16000){
      await reader.cancel();
      throw new Error('Request is too large.');
    }

    chunks.push(value);
  }

  const bytes=new Uint8Array(size);
  let offset=0;

  for(const chunk of chunks){
    bytes.set(chunk,offset);
    offset+=chunk.length;
  }

  return JSON.parse(new TextDecoder().decode(bytes));
}

